def han_only(text:str)->str:
    return "".join(HAN.findall(text))


def source_short_catalog(data:dict, workspace:ReviewWorkspace)->list[dict]:
    if data.get("dataset")!="faceface-source-checked-v5":
        raise ValueError("Unknown original-source short excerpt catalog")
    policy=data.get("policy",{})
    for field in ("no_fate_prediction","no_personality_health_fate_from_appearance",
                  "never_confirm_complete_type"):
        if policy.get(field) is not True:
            raise ValueError("Unsafe historical physiognomy site policy")
    items=[("card",r) for r in data.get("cards",[])]+[
        ("framework_note",r) for r in data.get("framework_notes",[])
    ]
    if len(items)!=13 or sum(x[0]=="card" for x in items)!=10:
        raise ValueError("The clean V5 pilot must retain exactly ten prior cards and three framework excerpts")
    out=[]
    seen_ids=set()
    for kind,row in items:
        sid=row.get("id")
        if not isinstance(sid,str) or sid in seen_ids:
            raise ValueError("Duplicate or invalid V5 original excerpt ID")
        seen_ids.add(sid)
        src=row.get("source")
        if not isinstance(src,dict):
            raise ValueError("Missing prior original-source provenance")
        url=src.get("source_url","")
        if not isinstance(url,str) or "NLC416-12jh002690-44091_" not in url:
            raise ValueError("Unexpected original PDF link")
        source="nlc-44091"
        idx=src.get("pdf_page_zero_based")
        if type(idx) is not int:
            raise ValueError("Invalid source PDF zero-based page index")
        workspace.page_paths(source,idx)
        # This is previous V5 AI visual source checking, NOT an independent signed
        # 2026 human reading. Keep the original source verification label as-is.
        verification=src.get("verification")
        if not isinstance(verification,str) or not (
            "scan" in verification.lower() or "pdf" in verification.lower()
        ):
            raise ValueError("Legacy source cannot be promoted without source-reference evidence")
        phrase=row.get("source_phrase") if kind=="card" else row.get("quote")
        if not isinstance(phrase,str) or not 2<=len(han_only(phrase))<=65:
            raise ValueError("V5 exact original short quote missing or implausible")
        source_hash=workspace.sources[source]["pdf_sha256"]
        if source_hash!=KNOWN_SCAN_SHA256[source]:
            raise ValueError("Wrong original source PDF SHA256")
        role_category=(row.get("organ") if kind=="card" else "historical_framework")
        title=row.get("traditional_name") if kind=="card" else row.get("title_zh")
        if not isinstance(title,str) or not title:
            raise ValueError("Missing original V5 item title")
        existing_constraints=[c.get("metric") for c in row.get("conditions",[])
                              if isinstance(c,dict)]
        if kind=="framework_note" and existing_constraints:
            raise ValueError("A historic framework note cannot be a live geometry trigger")
        out.append({
            "id":sid,
            "legacy_entry_kind":kind,
            "source_id":source,
            "pdf_page_zero_based":idx,
            "original_pdf_sha256":source_hash,
            "page_id":f"{source}:p{idx:03d}",
            "legacy_source_verification_label":verification,
            "source_provenance_quality":SOURCE_REVIEW_LABEL,
            "source_excerpt":phrase,
            "source_excerpt_sha256":hashlib.sha256(phrase.encode("utf-8")).hexdigest(),
            "legacy_display_title":title,
            "region":role_category,
            "legacy_existing_condition_metric_ids":existing_constraints,
            "source_excerpt_newly_human_reviewed":False,
            "this_experiment_may_add_live_rule":False,
        })
    return out


def official_role_texts(root:Path)->tuple[dict,dict[str,str]]:
    path=Path(root)
    files=[path/"SKILL.md",path/ADLER_NAME]+[
        path/"extractors"/f for f in ROLE_FILES.values()
    ]
    if not all(f.is_file() for f in files):
        raise ValueError("Missing official Cangjie original role prompt files")
    git=subprocess.run(
        ["git","-C",str(path),"rev-parse","HEAD"],
        text=True,capture_output=True,check=True,timeout=15
    ).stdout.strip()
    if git!=PINNED_CANGJIE_COMMIT:
        raise ValueError("Unexpected official Cangjie version")
    hashes={f.relative_to(path).as_posix():hashlib.sha256(f.read_bytes()).hexdigest()
            for f in files}
    texts={k:(path/"extractors"/filename).read_text(encoding="utf-8")
           for k,filename in ROLE_FILES.items()}
    adler=(path/ADLER_NAME).read_text(encoding="utf-8")
    if not all(len(x)>=500 for x in [adler,*texts.values()]):
        raise ValueError("Unexpectedly truncated pinned original Cangjie prompts")
    meta={
        "pinned_original_cangjie_commit":git,
        "official_upstream_files_sha256":hashes,
        "official_role_prompts_read_from_actual_pinned_checkout":True,
        "role_prompt_text_is_input_context_not_a_trained_model":True,
    }
    return meta,{"adler":adler,**texts}


class OllamaClient:
    def __init__(self,url:str,model:str=MODEL,timeout:int=480):
        parsed=urlsplit(url)
        if (parsed.scheme!="http" or parsed.hostname not in ("127.0.0.1","localhost")
            or parsed.port is None or parsed.path not in ("","/")
            or parsed.username or parsed.password or parsed.query or parsed.fragment):
            raise ValueError("Ollama must be loopback HTTP only")
        self.url=url.rstrip("/")
        self.model=model
        self.timeout=timeout
        self.client=build_opener(ProxyHandler({}))

    def installed(self)->dict:
        with self.client.open(Request(self.url+"/api/tags"),timeout=20) as r:
            models=json.loads(r.read(800000))["models"]
        matched=next((m for m in models if m.get("name")==self.model),None)
        if not matched:
            raise ValueError("Actual local Ollama model has not been installed")
        return {"model":self.model,"model_digest":matched.get("digest")}

    def infer(self,system:str,user:str,schema:dict)->dict:
        payload={
            "model":self.model,"stream":False,"format":schema,
            "options":{"temperature":0,"num_predict":900,"num_ctx":4096},
            "messages":[{"role":"system","content":system},
                        {"role":"user","content":user}],
        }
        req=Request(self.url+"/api/chat",
                    data=json.dumps(payload,ensure_ascii=False).encode("utf-8"),
                    headers={"Content-Type":"application/json"},method="POST")
        with self.client.open(req,timeout=self.timeout) as r:
            resp=json.loads(r.read(1_000_000))
        if resp.get("done") is not True or resp.get("model")!=self.model:
            raise ValueError("No genuinely completed matching-model inference")
        message=resp.get("message",{}).get("content")
        if not isinstance(message,str):
            raise ValueError("Actual LLM response content is not text")
        obj=json.loads(message)
        if not isinstance(obj,dict):
            raise ValueError("Actual LLM must return structured JSON")
        return obj


def accept_role_candidates(output:dict,role:str,source:list[dict])->tuple[list[dict],list[str]]:
    if role not in ROLE_FILES:
        raise ValueError("Unknown official Cangjie extractor role")
    if set(output)!={"candidates"} or not isinstance(output["candidates"],list):
        raise ValueError("Incorrect real model extractor schema")
    if len(output["candidates"])>2:
        raise ValueError("A small clean-source role may return at most two concepts")
    accepted=[]
    errors=[]
    expected_fields=set(ROLE_FORMAT["properties"]["candidates"]["items"]["required"])
    for row in output["candidates"]:
        if not isinstance(row,dict) or set(row)!=expected_fields:
            errors.append("role_output_wrong_structure")
            continue
        source_index=row["quote_id"]
        if type(source_index) is not int or not 0<=source_index<len(source):
            errors.append("unknown_original_quote_ID")
            continue
        strings=[row["title"],row["interpreted_morphology_or_historical_concept"],
                 row["photo_observability"],row["interference_or_limit"]]
        if (not all(isinstance(v,str) and v.strip() for v in strings)
            or len(strings[0])>60 or len(strings[1])>230
            or len(strings[3])>180 or strings[2] not in SAFE_OBS):
            errors.append("invalid_extractor_concept")
            continue
        ref=source[source_index]
        if role=="case" and ref["legacy_entry_kind"]=="framework_note":
            errors.append("historic_framework_note_not_a_case")
            continue
        accepted.append({
            "candidate_id":hashlib.sha256(
                (role+"|"+ref["id"]+"|"+strings[0]).encode("utf-8")
            ).hexdigest()[:18],
            "official_extractor_role":role,
            "quoted_source_index":source_index,
            "original_v5_source_id":ref["id"],
            "original_scan_page_id":ref["page_id"],
            "original_pdf_sha256":ref["original_pdf_sha256"],
            "exact_source_excerpt_SHA256":ref["source_excerpt_sha256"],
            "source_quote_restored_from_prior_source_catalog":ref["source_excerpt"],
            "llm_title_UNVERIFIED":row["title"],
            "llm_interpretation_UNVERIFIED":strings[1],
            "llm_photo_observability_GUESS":strings[2],
            "llm_interference_GUESS":strings[3],
            "not_independently_human_roi_checked":True,
            "auto_publish_to_Faceface":False,
            "has_model_fabricated_original_quote":False,
        })
    return accepted,errors


def run_agents(
    workspace:ReviewWorkspace,existing_catalog:dict,
    cangjie_root:Path,model:OllamaClient,
    private_root:Path,public_metadata:Path
)->dict:
    sources=source_short_catalog(existing_catalog,workspace)
    upstream,txt=official_role_texts(cangjie_root)
    model_meta=model.installed()
    # 13 fragment IDs, deterministic and source-bound; no OCR re-copy.
    reference_lines=[
        f"[{i}] {r['page_id']} | {r['region']} | {r['source_excerpt']}"
        for i,r in enumerate(sources)
    ]
    clean_input="\n".join(reference_lines)
    if len(clean_input)>3500:
        raise ValueError("Short original-text pilot unexpectedly large")
    private_root.mkdir(parents=True,exist_ok=True)
    # Adler is a partial structure hypothesis ONLY. Only quote data is input.
    adler_system=(
        "你是固定版本仓颉的 Stage0 Adler 原典阅读研究者。"
        "只允许根据输入的短句建立少量传统语汇结构假说。"
        "本试验仅有13条历史原页曾目视核查短句，绝非全书通读。"
        "禁止自创古籍引文、命运或人格断言，输出严格JSON。\n"
        +txt["adler"][:1600]
    )
    adler_user=(
        "请根据以下13个带原书页码的短引文，简述一条结构假说、"
        "最多三条术语和至少一个局限。不得称已读完268页。"
        "不要从面部外观推断真人健康、人格、财富或未来。\n"+clean_input
    )
    adler_success=False
    adler_error=None
    try:
        result=model.infer(adler_system,adler_user,ADLER_FORMAT)
        if set(result)!={"hypothesis","terms","limitations"} or \
           not isinstance(result["hypothesis"],str) or \
           not isinstance(result["terms"],list) or \
           not isinstance(result["limitations"],list) or \
           any(not isinstance(s,str) for s in result["terms"]+result["limitations"]):
            raise ValueError("Adler output does not conform to limited source schema")
        if len(result["terms"])>6 or len(result["limitations"])>6:
            raise ValueError("Adler generated an excessive ungrounded overview")
        adler_success=True
        atomic_write(private_root/"ADLER_SAMPLE_ONLY_PRIVATE.json",
                     (json.dumps({"model":model.model,"scope":"13_preexisting_short_phrases_not_whole_book",
                                  "result":result},ensure_ascii=False,indent=2)+"\n").encode("utf-8"))
    except (ValueError,KeyError,TypeError,OSError,HTTPError) as exc:
        adler_error=type(exc).__name__
    entries=[]
    call_stats=[]
    for role in ROLE_FILES:
        # Keep each role independent: it never sees Adler output/another
        # extractor's concept, only the same 13 original short phrases.
        system=(
            "你是仓颉官方固定版本的独立"+role+"提取器。"
            "上文为实际官方角色提示的一部分。"
            "本输入是13条短古籍引文，原文已由程序编号且禁止抄写引文。"
            "只从编号0到12中选quote_id，返回0至2个真实合适的候选。"
            "有适用的传统术语/形态描述就不要因谨慎全部返回空；"
            "确实没有案例或反例时允许返回空候选。"
            "输出严格JSON，只分析历史面部形态与文化术语，"
            "绝不预测真人命运、健康或性格。"
            "\n官方源文件原文节选：\n"+txt[role][:1200]
        )
        user=(
            "从下列原书短引文中挑最多2条真正符合你角色的内容。"
            "quote_id是下面方括号内的整数，不许复制或改写古籍原文，"
            "不要把古代相貌命运断语当作今天的事实。"
            "可观察性只能选partial_photo_observable、"
            "not_currently_measured、historical_framework_only、unclear。"
            "如属于历史概念，应解释其文化术语含义。"
            "\n原书短引文及页码：\n"+clean_input
        )
        record={"role":role,"actual_independent_Ollama_inference":False,
                "schema_valid":False,"source_id_matched_candidates":0,
                "rejected_candidate_count":0,"error_type":None,
                "real_model_requests_attempted":0,
                "first_response_invalid_JSON":False,
                "rejected_candidate_reasons":[]}
        try:
            record["real_model_requests_attempted"]+=1
            try:
                output=model.infer(system,user,ROLE_FORMAT)
            except json.JSONDecodeError:
                # The preceding REAL original-source experiment completed only
                # 3/5 roles: case + counter_example emitted malformed JSON.
                # ONE more REAL independent request for that same role uses
                # an even shorter (still pinned upstream-derived) instruction,
                # the SAME fixed source references and the SAME JSON schema.
                # No mock/empty answer is silently substituted.
                record["first_response_invalid_JSON"]=True
                short_system=(
                    "仓颉固定官方角色："+role+"。请严格使用JSON Schema返回一个对象。"
                    "若输入确实没有这种类型的古籍证据，返回 {\"candidates\": []}。"
                    "有证据时仅返回1条，quote_id为0到12整数，其他字段简短。"
                    "禁止编造引文、当代人格和命运判断。"
                    "\n固定仓颉原版角色提示节选：\n"+txt[role][:650]
                )
                short_user=(
                    "同一原书来源13条短句，仅重新请求JSON格式，不改变参考资料。"
                    "输出仅JSON，没有Markdown或解释。\n"+clean_input
                )
                record["real_model_requests_attempted"]+=1
                output=model.infer(short_system,short_user,ROLE_FORMAT)
            record["actual_independent_Ollama_inference"]=True
            accepted,rejected=accept_role_candidates(output,role,sources)
            record["schema_valid"]=True
            record["source_id_matched_candidates"]=len(accepted)
            record["rejected_candidate_count"]=len(rejected)
            record["rejected_candidate_reasons"]=rejected
            entries.extend(accepted)
        except (ValueError,KeyError,TypeError,OSError,HTTPError) as exc:
            record["error_type"]=type(exc).__name__
        call_stats.append(record)
        print(json.dumps(record,ensure_ascii=False),flush=True)
    # The model's original source 'quote' ALWAYS comes from the prior catalog
    # by source ID. The model cannot supply historical original words itself.
    atomic_write(private_root/"five-roles-CLEAN-V5-CANDIDATES-not-reviewed.json",
                 (json.dumps({
                     "model":model_meta,
                     "source_catalog_count":len(sources),
                     "source_status":SOURCE_REVIEW_LABEL,
                     "source_records":sources,
                     "candidates_NOT_LIVE":entries,
                     "role_statistics":call_stats,
                 },ensure_ascii=False,indent=2)+"\n").encode("utf-8"))
    stats={
        "kind":"M16.13_ACTUAL_PINNED_CANGJIE_CLEAN_SHORT_EXCERPT_SEMANTIC_LLM",
        "official_upstream":upstream,
        "model":model_meta,
        "original_1925_PDF_sha256":{
            x:workspace.sources[x]["pdf_sha256"] for x in workspace.sources
        },
        "preexisting_AI_scan_visual_legacy_excerpt_count":len(sources),
        "actual_independently_human_signed_new_short_ROIs":0,
        "real_Adler_sample_model_completed":adler_success,
        "Adler_scope":"13_SHORT_V5_LEGACY_PHRASES_NOT_268_PAGE_BOOK",
        "adler_failure_type":adler_error,
        "independent_real_extractor_roles_attempted":len(call_stats),
        "real_model_requests_including_strict_JSON_retries":sum(
            x["real_model_requests_attempted"] for x in call_stats
        ),
        "independent_real_extractor_role_calls_completed":sum(
            r["actual_independent_Ollama_inference"] for r in call_stats
        ),
        "real_extractor_roles_returning_source_bound_candidates":sum(
            r["source_id_matched_candidates"]>0 for r in call_stats
        ),
        "total_LLM_candidate_concepts_source_quote_id_bound":len(entries),
        "source_ids_for_matched_candidate_concepts":sorted(set(
            item["original_v5_source_id"] for item in entries
        )),
        "source_id_matched_candidate_count_per_role":{
            s["role"]:s["source_id_matched_candidates"] for s in call_stats
        },
        "role_calls":call_stats,
        "all_model_interpretations_source_unverified":True,
        "never_claimed_whole_book_agents_complete":True,
        "original_OCR_CER_measured":False,
        "model_fabricated_original_quotes_accepted":0,
        "new_source_original_full_pages_human_signed":0,
        "new_live_Faceface_rules":0,
        "public_report_contains_any_ancient_short_quote_or_LLM_analysis":False,
        "next_action":"Review source-bound semantic candidate quality against actual 1925 original; "
                      "separate shape observation, figurative language and unobservable life assertions."
    }
    atomic_write(public_metadata,
                 (json.dumps(stats,ensure_ascii=False,indent=2)+"\n").encode("utf-8"))
    print(json.dumps({k:v for k,v in stats.items() if k not in (
        "official_upstream","role_calls"
    )},ensure_ascii=False),flush=True)
    return stats


def main()->None:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--scan-dir",type=Path,required=True)
    p.add_argument("--catalog",type=Path,default=Path(
        "src/knowledge/maiyi-source-checked-v5.json"
    ))
    p.add_argument("--upstream",type=Path,required=True)
    p.add_argument("--private-dir",type=Path,required=True)
    p.add_argument("--out-metadata",type=Path,required=True)
    p.add_argument("--ollama-url",default="http://127.0.0.1:11434")
    p.add_argument("--model",default=MODEL)
    a=p.parse_args()
    workspace=ReviewWorkspace(a.scan_dir,a.private_dir/"missing-ocr",
                              a.private_dir/"missing-full-human-review")
    catalog=json.loads(a.catalog.read_text(encoding="utf-8"))
    report=run_agents(workspace,catalog,a.upstream,
                      OllamaClient(a.ollama_url,a.model),
                      a.private_dir/"semantic-results",a.out_metadata)
    if (not report["real_Adler_sample_model_completed"]
        or report["independent_real_extractor_role_calls_completed"]!=5
        or report["total_LLM_candidate_concepts_source_quote_id_bound"]<1):
        raise SystemExit("Real clean source LLM pilot QUALITY GATE FAILED: do not call it distillation success")


if __name__=="__main__":
    main()
